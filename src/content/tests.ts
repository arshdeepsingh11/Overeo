export type Evidence = "guideline" | "established" | "emerging" | "exploratory";

export const EVIDENCE: Record<Evidence, { label: string; desc: string; tone: "good" | "signal" | "" | "alert" }> = {
  guideline: { label: "Guideline-backed", desc: "Recommended by a major clinical guideline for the situation it's used in.", tone: "good" },
  established: { label: "Established", desc: "Widely used in clinical care with well-understood meaning.", tone: "good" },
  emerging: { label: "Emerging", desc: "Promising and clinically available, but its role in decisions is still being defined.", tone: "signal" },
  exploratory: { label: "Exploratory", desc: "Mainly a research tool today. Interesting to track, rarely changes a decision.", tone: "alert" },
};

